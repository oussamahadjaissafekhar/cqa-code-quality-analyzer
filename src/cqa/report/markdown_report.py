"""Markdown summary, suitable for GitHub Step Summary or a PR comment."""

from __future__ import annotations

from ..models import ALL_SEVERITIES, AnalysisResult, Finding
from .redact import display_snippet

MAX_LISTED = 20
MAX_ERRORS = 10


def _escape(value: str) -> str:
    """Escape table-breaking characters; reports are not HTML by default."""

    return value.replace("|", "\\|").replace("\n", " ").replace("\r", " ")


def _location(finding: Finding) -> str:
    return f"`{finding.path}:{finding.start_line}:{finding.start_col}`"


def _finding_row(finding: Finding) -> str:
    message = _escape(finding.message)
    snippet = display_snippet(finding)
    if snippet:
        message += f"<br><code>{_escape(snippet)}</code>"
    return (
        f"| {finding.severity.value} | `{finding.rule_id}` | {_location(finding)} | {message} |"
    )


def render_markdown(result: AnalysisResult) -> str:
    summary = result.summary
    status = "❌ Failed" if summary.failed else "✅ Passed"
    lines: list[str] = [
        "## CQA analysis",
        "",
        (
            f"**{status}** · score **{summary.score}/100** · "
            f"{summary.findings} finding(s) in {summary.files_scanned} file(s)"
        ),
        "",
        "| Severity | Count |",
        "| --- | ---: |",
    ]
    for severity in ALL_SEVERITIES:
        lines.append(f"| {severity.value} | {summary.by_severity.get(severity.value, 0)} |")

    if result.findings:
        lines.extend(
            [
                "",
                f"### Findings (top {min(MAX_LISTED, len(result.findings))})",
                "",
                "| Severity | Rule | Location | Message |",
                "| --- | --- | --- | --- |",
            ]
        )
        lines.extend(_finding_row(finding) for finding in result.findings[:MAX_LISTED])
        if len(result.findings) > MAX_LISTED:
            lines.append(
                f"\n_… {len(result.findings) - MAX_LISTED} more finding(s) omitted "
                f"(see JSON/SARIF artifacts)._"
            )

    if summary.truncated:
        lines.extend(
            [
                "",
                f"> Output truncated to the configured `--max-findings`; "
                f"all {summary.findings} findings are counted in the summary.",
            ]
        )

    if result.errors:
        lines.extend(["", "### Parser / IO errors", ""])
        for error in result.errors[:MAX_ERRORS]:
            lines.append(f"- `{error.path}` ({error.kind}): {_escape(error.message)}")
        if len(result.errors) > MAX_ERRORS:
            lines.append(f"- … {len(result.errors) - MAX_ERRORS} more error(s)")

    lines.extend(
        [
            "",
            f"_Generated by cqa {result.tool.version} "
            f"(parser {result.tool.parser_version}, schema v{result.schema_version}) at "
            f"{result.generated_at}._",
            "",
        ]
    )
    return "\n".join(lines)
